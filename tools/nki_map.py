#!/usr/bin/env python3
"""Correlate NKI source calls with the NEFF instructions they produced, over the whole corpus.

For every instruction slot whose debug info names an NKI source line (artifacts/corpus), read
that line of the kernel source; if it holds no NKI call, walk back up to 6 lines to the start of
the statement. Extract the NKI API names on it (`nisa.x`, `nl.x`, `ncc.x`) and count which
(engine, opcode) each API produced. Writes docs/generated/nki_to_isa.md and
artifacts/reference/nki_to_isa.json.

Run with workspace/.venv.
"""

import glob
import json
import os
import re
import sys
from collections import Counter, defaultdict

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import isa  # noqa: E402

ART = os.path.join(HERE, "..", "artifacts")
API = re.compile(r"\b(nisa|nl|ncc)\.([a-z_][a-z0-9_]*)\s*\(")
_src_cache = {}


def src_lines(path):
    if path not in _src_cache:
        try:
            _src_cache[path] = open(path).read().split("\n")
        except OSError:
            _src_cache[path] = None
    return _src_cache[path]


def apis_at(path, line):
    lines = src_lines(path)
    if not lines or not (1 <= line <= len(lines)):
        return []
    for back in range(0, 7):
        i = line - 1 - back
        if i < 0:
            break
        found = [f"{m.group(1)}.{m.group(2)}" for m in API.finditer(lines[i])]
        if found:
            return found
    return []


def main():
    counts = defaultdict(Counter)        # api -> (engine, opcode) -> slots
    kernels = defaultdict(set)
    for p in sorted(glob.glob(os.path.join(ART, "corpus", "*.parquet"))):
        df = pd.read_parquet(p, columns=["tag", "engine", "op", "kernel_file", "kernel_line"])
        df = df[df.kernel_line.notna() & df.kernel_file.notna()]
        for (kf, kl, eng, op), n in df.groupby(["kernel_file", "kernel_line", "engine", "op"]).size().items():
            names = apis_at(kf, int(kl))
            # the innermost NKI call on a line is the one that issues the instruction;
            # take the first nisa.* name, else the last nl.* / ncc.* name
            pick = next((a for a in names if a.startswith("nisa.")), names[-1] if names else "<no NKI call on line>")
            counts[pick][(eng, isa.OPCODES.get(int(op), hex(int(op))))] += int(n)
            kernels[pick].add(os.path.basename(os.path.dirname(os.path.dirname(kf))) if kf else "")
    out = {a: {f"{e}:{o}": n for (e, o), n in c.most_common()} for a, c in counts.items()}
    json.dump(out, open(os.path.join(ART, "reference", "nki_to_isa.json"), "w"), indent=1)
    lines = ["# NKI call -> NEFF instructions (from the corpus)", "",
             "Generated by `tools/nki_map.py`. For every instruction slot, the NKI source line in its "
             "debug info was read and the NKI call on it identified; the table counts which engine "
             "and opcode each call produced over all 14 kernels (both subgraphs). A call can produce "
             "several instructions (for example its semaphore waits, `EVENT_SEMAPHORE`, carry the "
             "same source line). `<no NKI call on line>` covers compiler-made instructions "
             "attributed to a line without a call.", "",
             "| NKI call | slots | kernels | engine:opcode (slots) |", "|---|---|---|---|"]
    for a, c in sorted(counts.items(), key=lambda kv: -sum(kv[1].values())):
        top = ", ".join(f"{e}:{o} ({n})" for (e, o), n in c.most_common(6))
        lines.append(f"| `{a}` | {sum(c.values())} | {len(kernels[a])} | {top} |")
    os.makedirs(os.path.join(HERE, "..", "docs", "generated"), exist_ok=True)
    open(os.path.join(HERE, "..", "docs", "generated", "nki_to_isa.md"), "w").write("\n".join(lines) + "\n")
    print(f"{len(counts)} NKI calls mapped")


if __name__ == "__main__":
    main()
