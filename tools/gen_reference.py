#!/usr/bin/env python3
"""Generate docs/generated/{opcodes,structs,enums}.md from the extracted vendor data.

opcodes.md: every NeuronCore-v3 opcode with its struct, how the struct was decided, corpus
counts per engine, profiler name and verification pass rate. structs.md: wire layout of every
struct an opcode uses. enums.md: the enum types those structs use. Run with workspace/.venv.
"""

import glob
import json
import os
import sys
from collections import Counter, defaultdict

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import isa  # noqa: E402

ART = os.path.join(HERE, "..", "artifacts")
OUT = os.path.join(HERE, "..", "docs", "generated")


def corpus_stats():
    count, engines = Counter(), defaultdict(Counter)
    for p in sorted(glob.glob(os.path.join(ART, "corpus", "*.parquet"))):
        df = pd.read_parquet(p, columns=["op", "engine"])
        for (op, eng), n in df.groupby(["op", "engine"]).size().items():
            count[int(op)] += int(n)
            engines[int(op)][eng] += int(n)
    return count, engines


def short(t):
    return (t or "").split(".")[-1].replace("NEURON_ISA_TPB_", "")


def opcodes_md(count, engines, verified):
    out = ["# Opcode reference (NeuronCore-v3, Trainium2)", "",
           "Generated by `tools/gen_reference.py`. *struct* is the layout `tools/isa.py` uses. "
           "*source*: `dispatch` = neuron-dbg's own disassembler; `supplement` = established "
           "from the corpus (`artifacts/reference/isa_layout_supplement.json`). *pass* = share "
           "of field checks against the profiler's text that passed (`tools/verify_isa.py`); "
           "pseudo-instructions are compared with their runtime expansion, so a low rate there "
           "is not a decoder error.", "",
           "| value | opcode | struct | source | slots | engines | profiler name | pass |",
           "|---|---|---|---|---|---|---|---|"]
    for v in sorted(isa.OPCODES):
        name, st = isa.OPCODES[v], isa.STRUCT_OF.get(v)
        src = isa.STRUCT_SOURCE.get(v, "")
        src = "supplement" if src.startswith("supplement") else ("dispatch" if src else "")
        ver = verified.get(name, {})
        pr = ver.get("pass_rate")
        eng = ", ".join(f"{e} {n}" for e, n in engines[v].most_common()) if v in engines else ""
        out.append(f"| 0x{v:02x} | `{name}` | {('`' + st + '`') if st else '-'} | {src} | "
                   f"{count.get(v, 0)} | {eng} | {', '.join(ver.get('profiler_names', []))} | "
                   f"{'' if pr is None else f'{pr:.3f}'} |")
    return "\n".join(out) + "\n"


def structs_md():
    used = sorted(set(isa.STRUCT_OF.values()) | set(isa.EXTENSION_STRUCT.values()))
    out = ["# Instruction struct layouts", "",
           "Generated by `tools/gen_reference.py` from the vendor accessors in neuron-dbg "
           "(`tools/isa_layout.py`) plus the supplement. One row per leaf field in wire order. "
           "*bits* is `shift/mask` for bitfields; *n* is the array length (elements `stride` "
           "bytes apart). Fields at the same offset are union members: the marker byte or an "
           "`*_src` field says which one applies.", ""]
    for st in used:
        try:
            fs = isa.fields(st)
        except KeyError:
            continue
        users = [isa.OPCODES[v] for v, s in isa.STRUCT_OF.items() if s == st and v in isa.OPCODES]
        users += [f"extension of {k}" for k, s in isa.EXTENSION_STRUCT.items() if s == st]
        out += [f"## `{st}`", "", "Used by: " + ", ".join(f"`{u}`" for u in users), "",
                "| offset | width | bits | n | field | type |", "|---|---|---|---|---|---|"]
        for f in fs:
            bits = ""
            if f["shift"] or f["mask"] is not None:
                bits = f"{f['shift']}/" + (f"{f['mask']:#x}" if f["mask"] is not None else "rest")
            n = f"{f['count']}" if f["stride"] else ""
            sign = " (signed)" if f["signed"] else ""
            out.append(f"| {f['offset']} | {f['width']} | {bits} | {n} | `{f['name']}` | "
                       f"{short(f['type'])}{sign} |")
        out.append("")
    return "\n".join(out) + "\n"


def enums_md():
    types = set()
    for st in set(isa.STRUCT_OF.values()) | set(isa.EXTENSION_STRUCT.values()):
        try:
            types.update(f["type"] for f in isa.fields(st) if f["type"] in isa.ENUMS)
        except KeyError:
            pass
    out = ["# Enum values", "", "Generated by `tools/gen_reference.py` from the vendor constants "
           "in neuron-dbg's DWARF (NeuronCore-v3 names where versions differ).", ""]
    for t in sorted(types, key=short):
        out += [f"## {short(t)}", "", "| value | name |", "|---|---|"]
        out += [f"| {v} | `{n}` |" for v, n in sorted(isa.ENUMS[t].items())]
        out.append("")
    return "\n".join(out) + "\n"


def main():
    os.makedirs(OUT, exist_ok=True)
    count, engines = corpus_stats()
    vpath = os.path.join(ART, "reference", "opcode_struct_v3.json")
    verified = json.load(open(vpath)) if os.path.exists(vpath) else {}
    for name, text in (("opcodes.md", opcodes_md(count, engines, verified)),
                       ("structs.md", structs_md()), ("enums.md", enums_md())):
        open(os.path.join(OUT, name), "w").write(text)
        print(f"wrote docs/generated/{name} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
